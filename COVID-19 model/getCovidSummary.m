function [S,nEff] = getCovidSummary(y)
% Summary statistics for the COVID-19 screening Bayes net (31 statistics).
%
% Input:    y     n x 14 matrix of states in {1,2}: [COV, 7 symptoms, 6 odours]
% Outputs:  S     1 x 31 summary statistics, laid out as
%                   S1 ( 1) COVID-19 prevalence
%                   S2 (14) symptom rates given COV        (7 x 2, negative stratum first)
%                   S3 (12) odour state-1 rates given COV  (6 x 2, negative stratum first)
%                   S4 ( 4) 2nd and 3rd central moments of the odour count (2 x 2)
%           nEff  1 x 31 stratum size behind each statistic
%
% 31 statistics against 37 free parameters. S1-S2 are sufficient for the blocks
% whose parent (COV) is observed; S3-S4 identify the hidden olfactory status,
% since the odours are conditionally independent GIVEN sKor and any departure of
% the count spread from independence is generated by it. Without S4 the three
% states of sKor are not identifiable. S4 is not a proportion, so the driver
% bootstraps the standard errors of all statistics rather than using binomial ones.
% --------------------- Pedro Saa UC 2026 ---------------------------------
n   = size(y,1);
covState = y(:,1);
sym = y(:,2:8);
odo = y(:,9:14);

S    = zeros(1,31);
nEff = zeros(1,31);

% S1: prevalence. State 2 is positive, under the false==1/true==2 convention
% applied to the data by the driver.
S(1)    = sum(covState==2)/n;
nEff(1) = n;

% Stratum masks and sizes, computed once
m1 = (covState==1); n1 = max(sum(m1),1);                                         % COVID-negative; guard against an empty stratum
m2 = (covState==2); n2 = max(sum(m2),1);                                         % COVID-positive

% S2: symptom rates conditional on the COVID-19 status
S(2:8)     = sum(sym(m1,:)==1,1)/n1;   nEff(2:8)     = n1;
S(9:15)    = sum(sym(m2,:)==1,1)/n2;   nEff(9:15)    = n2;

% S3: odour rates conditional on the COVID-19 status
S(16:21)   = sum(odo(m1,:)==1,1)/n1;   nEff(16:21)   = n1;
S(22:27)   = sum(odo(m2,:)==1,1)/n2;   nEff(22:27)   = n2;

% S4: 2nd and 3rd central moments of the odour count, per COV stratum. These
% replaced a 7-bin histogram collinear with S3 that carried 42% of the noise
% floor. Written out rather than via moment(), too costly on this loop.
K1 = sum(odo(m1,:)==1,2);   c1 = numel(K1);   d1 = K1 - sum(K1)/c1;
K2 = sum(odo(m2,:)==1,2);   c2 = numel(K2);   d2 = K2 - sum(K2)/c2;
S(28) = sum(d1.^2)/c1;   S(29) = sum(d1.^3)/c1;   nEff(28:29) = n1;
S(30) = sum(d2.^2)/c2;   S(31) = sum(d2.^3)/c2;   nEff(30:31) = n2;
